//! `cargo xtask bundle`: package an app binary for a target that cannot run
//! a bare executable.
//!
//! ```text
//! cargo xtask bundle --target ios-sim|ios|android|web -p <package> [--bin <name>]
//!     [--release] [--run] [--sign <identity>] [--profile <file>]
//! ```
//!
//! iOS: the binary is built for `aarch64-apple-ios-sim` (`ios-sim`) or
//! `aarch64-apple-ios` (`ios`) and wrapped in an `.app` with its Info.plist
//! under `<target-dir>/bundle/<target>/`. It is signed ad-hoc unless
//! `--sign` names an identity; a device build also embeds the `--profile`
//! provisioning profile and signs with its entitlements. `--run` installs it on
//! the booted simulator and launches it (simulator only).
//!
//! Android: the binary is linked as a shared library exporting `main` and
//! `JNI_OnLoad`, and packed with the `dev.viso` Java shell into a signed APK
//! (debug keystore) under `<target-dir>/bundle/android/`. `--run` installs it
//! on the device `adb` sees and launches it.
//!
//! Web: the binary is built for `wasm32-unknown-unknown`, its JS glue
//! generated by the `wasm-bindgen` CLI (the version `Cargo.lock` pins), and
//! an `index.html` that loads it written beside them under
//! `<target-dir>/bundle/web/`. `--run` serves the directory on localhost (a
//! secure context, as WebGPU requires) until interrupted.

use std::io::{BufRead, BufReader, Write};
use std::net::{TcpListener, TcpStream};
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};

use viso_package::{android, apple, web};

struct Options {
    target: String,
    package: String,
    bin: Option<String>,
    release: bool,
    run: bool,
    sign: Option<String>,
    profile: Option<PathBuf>,
}

fn parse(args: &[String]) -> Result<Options, String> {
    let mut o = Options {
        target: String::new(),
        package: String::new(),
        bin: None,
        release: false,
        run: false,
        sign: None,
        profile: None,
    };
    let mut it = args.iter();
    while let Some(arg) = it.next() {
        let mut value = || it.next().cloned().ok_or(format!("{arg} needs a value"));
        match arg.as_str() {
            "--target" => o.target = value()?,
            "-p" | "--package" => o.package = value()?,
            "--bin" => o.bin = Some(value()?),
            "--release" => o.release = true,
            "--run" => o.run = true,
            "--sign" => o.sign = Some(value()?),
            "--profile" => o.profile = Some(PathBuf::from(value()?)),
            other => return Err(format!("unknown argument {other:?}")),
        }
    }
    if o.target.is_empty() || o.package.is_empty() {
        return Err("--target and -p are required".into());
    }
    Ok(o)
}

pub(crate) fn bundle(args: &[String]) -> ExitCode {
    let options = match parse(args) {
        Ok(o) => o,
        Err(e) => {
            eprintln!("bundle: {e}\nusage: {USAGE}");
            return ExitCode::FAILURE;
        }
    };
    let result = match options.target.as_str() {
        "ios-sim" => ios(&options, true),
        "ios" => ios(&options, false),
        "android" => android(&options),
        "web" => web(&options),
        other => Err(format!(
            "unknown bundle target {other:?} (ios-sim, ios, android, web)"
        )),
    };
    match result {
        Ok(path) => {
            println!("{}", path.display());
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("bundle: {e}");
            ExitCode::FAILURE
        }
    }
}

const USAGE: &str = "cargo xtask bundle --target ios-sim|ios|android|web -p <package> \
[--bin <name>] [--release] [--run] [--sign <identity>] [--profile <file>]";

/// Run `cmd`, failing with its name if it does not succeed.
fn run(cmd: &mut Command) -> Result<(), String> {
    let status = cmd
        .status()
        .map_err(|e| format!("{:?}: {e}", cmd.get_program()))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("{:?} failed ({status})", cmd.get_program()))
    }
}

/// Run `cmd` and capture its stdout.
fn output(cmd: &mut Command) -> Result<String, String> {
    let out = cmd
        .output()
        .map_err(|e| format!("{:?}: {e}", cmd.get_program()))?;
    if !out.status.success() {
        return Err(format!(
            "{:?} failed: {}",
            cmd.get_program(),
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    Ok(String::from_utf8_lossy(&out.stdout).into_owned())
}

/// The executable path of the `--bin` artifact in cargo's JSON messages.
fn executable(messages: &str) -> Option<PathBuf> {
    messages
        .lines()
        .filter(|l| l.contains("\"reason\":\"compiler-artifact\""))
        .filter_map(|l| {
            let at = l.find("\"executable\":\"")? + "\"executable\":\"".len();
            let end = l[at..].find('"')?;
            Some(PathBuf::from(l[at..at + end].replace("\\\\", "\\")))
        })
        .next_back()
}

/// `cargo build` (or `cargo rustc` with `rustc_args`) of the `--bin` of the
/// package for `triple`: the executable it built and the target directory.
fn cargo(
    o: &Options,
    bin: &str,
    triple: &str,
    rustc_args: &[&str],
    env: &[(String, PathBuf)],
) -> Result<(PathBuf, PathBuf), String> {
    let mut cargo = Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()));
    cargo
        .current_dir(crate::workspace_root())
        .arg(if rustc_args.is_empty() {
            "build"
        } else {
            "rustc"
        })
        .arg("--message-format=json-render-diagnostics")
        .args(["-p", &o.package, "--bin", bin, "--target", triple])
        .args(o.release.then_some("--release"));
    if !rustc_args.is_empty() {
        cargo.arg("--").args(rustc_args);
    }
    cargo.envs(env.iter().map(|(k, v)| (k, v)));
    let built = executable(&output(&mut cargo)?).ok_or("cargo reported no executable")?;
    let target_dir = built
        .ancestors()
        .nth(3)
        .ok_or("unexpected artifact path")?
        .to_path_buf();
    Ok((built, target_dir))
}

fn ios(o: &Options, simulator: bool) -> Result<PathBuf, String> {
    let (target, triple) = if simulator {
        ("ios-sim", apple::simulator_triple())
    } else {
        ("ios", apple::DEVICE_TRIPLE)
    };
    if o.run && !simulator {
        return Err(
            "--run installs on the simulator only; install a device build with \
             `xcrun devicectl device install app --device <id> <app>`"
                .into(),
        );
    }
    let bin = o.bin.clone().unwrap_or_else(|| o.package.clone());
    let (built, target_dir) = cargo(o, &bin, triple, &[], &[])?;
    let out = target_dir.join("bundle").join(target);
    let app = apple::bundle(&built, &out, &bin, simulator)?;
    let profile = o.profile.as_deref().filter(|_| !simulator);
    apple::sign(
        &app.path,
        o.sign.as_deref(),
        profile,
        &out.join(format!("{bin}.sign")),
    )?;

    if o.run {
        run(Command::new("xcrun")
            .args(["simctl", "install", "booted"])
            .arg(&app.path))
        .map_err(|e| format!("{e} (boot a simulator first: xcrun simctl boot <device>)"))?;
        run(Command::new("xcrun").args(["simctl", "launch", "booted", &app.id]))?;
    }
    Ok(app.path)
}

/// The Android SDK: `$ANDROID_HOME`/`$ANDROID_SDK_ROOT`, then the one
/// `viso android use` installed, then the default location.
pub(crate) fn android_sdk() -> Result<android::Sdk, String> {
    let viso = std::env::var_os("VISO_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".viso")))
        .map(|root| root.join("android/sdk"))
        .filter(|sdk| sdk.is_dir());
    android::Sdk::locate(viso.as_deref())
}

fn android(o: &Options) -> Result<PathBuf, String> {
    let root = crate::workspace_root();
    let sdk = android_sdk()?;
    let bin = o.bin.clone().unwrap_or_else(|| o.package.clone());
    let abi = android::Abi::Arm64;
    let (built, target_dir) = cargo(
        o,
        &bin,
        abi.triple(),
        android::RUSTC_ARGS,
        &sdk.cargo_env(abi),
    )?;
    let out = target_dir.join("bundle/android").join(&bin);
    // The Java shell, and the services' Java half.
    let shell = android::Shell {
        java: vec![
            root.join("crates/platform/android/java"),
            root.join("crates/services/android/java"),
        ],
        manifest: root.join("crates/platform/android/AndroidManifest.xml"),
    };
    let flavor = if o.release {
        android::Flavor::Release
    } else {
        android::Flavor::Dev
    };
    let apk = sdk.package(&built, abi, &out, &bin, &shell, flavor)?;

    if o.run {
        run(Command::new(&sdk.adb)
            .args(["install", "-r"])
            .arg(&apk.path))?;
        run(Command::new(&sdk.adb).args(["shell", "am", "start", "-n", &apk.component()]))?;
    }
    Ok(apk.path)
}

fn web(o: &Options) -> Result<PathBuf, String> {
    let bin = o.bin.clone().unwrap_or_else(|| o.package.clone());
    let (built, target_dir) = cargo(o, &bin, web::TRIPLE, &[], &[])?;
    let out = target_dir.join("bundle/web").join(&bin);
    web::bindgen(&built, &out, &bin)?;
    let index = web::write_index(&out, &bin)?;
    if o.run {
        serve(&out)?;
    }
    Ok(index)
}

/// Serve `dir` on the first free localhost port from 8000, one request at
/// a time, until the process is interrupted.
fn serve(dir: &Path) -> Result<(), String> {
    let listener = (8000..8100)
        .find_map(|port| TcpListener::bind(("127.0.0.1", port)).ok())
        .ok_or("no free port in 8000..8100")?;
    let addr = listener.local_addr().map_err(|e| e.to_string())?;
    println!("serving {} at http://{addr}/ (Ctrl-C stops)", dir.display());
    for stream in listener.incoming().filter_map(Result::ok) {
        let _ = respond(dir, stream);
    }
    Ok(())
}

fn respond(dir: &Path, mut stream: TcpStream) -> std::io::Result<()> {
    let mut request = String::new();
    BufReader::new(&stream).read_line(&mut request)?;
    let mut words = request.split_whitespace();
    let (method, target) = (words.next().unwrap_or(""), words.next().unwrap_or(""));
    let file = (method == "GET" || method == "HEAD")
        .then(|| web::resolve(dir, target))
        .flatten()
        .and_then(|path| std::fs::read(&path).ok().map(|body| (path, body)));
    let (status, kind, body) = match file {
        Some((path, body)) => ("200 OK", web::mime(&path), body),
        None => ("404 Not Found", "text/plain", b"not found".to_vec()),
    };
    write!(
        stream,
        "HTTP/1.1 {status}\r\nContent-Type: {kind}\r\nContent-Length: {}\r\nCache-Control: no-store\r\nConnection: close\r\n\r\n",
        body.len()
    )?;
    if method != "HEAD" {
        stream.write_all(&body)?;
    }
    stream.flush()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_bundle_arguments() {
        let args: Vec<String> = ["--target", "android", "-p", "app", "--release"]
            .iter()
            .map(|s| s.to_string())
            .collect();
        let o = parse(&args).unwrap();
        assert_eq!((o.target.as_str(), o.package.as_str()), ("android", "app"));
        assert!(o.release && !o.run && o.bin.is_none() && o.sign.is_none());
        assert!(parse(&args[..2]).is_err());
        let signed: Vec<String> = [
            "--target",
            "ios",
            "-p",
            "app",
            "--sign",
            "Dev",
            "--profile",
            "p",
        ]
        .iter()
        .map(|s| s.to_string())
        .collect();
        let o = parse(&signed).unwrap();
        assert_eq!(o.sign.as_deref(), Some("Dev"));
        assert_eq!(o.profile, Some(PathBuf::from("p")));
        assert!(parse(&["--frobnicate".to_string()]).is_err());
    }

    #[test]
    fn finds_the_last_executable() {
        let messages = concat!(
            "{\"reason\":\"compiler-artifact\",\"executable\":null}\n",
            "{\"reason\":\"compiler-artifact\",\"executable\":\"/t/aarch64-linux-android/debug/app\"}\n",
            "{\"reason\":\"build-finished\",\"success\":true}\n",
        );
        assert_eq!(
            executable(messages),
            Some(PathBuf::from("/t/aarch64-linux-android/debug/app"))
        );
    }
}
