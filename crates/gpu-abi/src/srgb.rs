/// sRGB byte `b` as linear light.
#[inline(always)]
pub fn decode(b: u8) -> f32 {
    DECODE[b as usize]
}

/// Linear light `v`, clamped to `[0, 1]`, as an sRGB byte; NaN is 0.
#[inline(always)]
pub fn encode(v: f32) -> u8 {
    ENCODE[(v.clamp(0.0, 1.0) * 4095.0 + 0.5) as usize]
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_byte_survives_a_decode_and_an_encode() {
        for b in 0..=255u8 {
            assert_eq!(encode(decode(b)), b, "{b}");
        }
        assert_eq!(encode(f32::NAN), 0);
        assert_eq!(encode(2.0), 255);
        assert_eq!(decode(0), 0.0);
        assert_eq!(decode(255), 1.0);
    }

    #[test]
    fn mid_grey_is_the_familiar_value() {
        // 50% linear light is sRGB 188; sRGB 128 is about 21.6% linear light.
        assert_eq!(encode(0.5), 188);
        assert!((decode(128) - 0.2158).abs() < 1e-3);
    }
}
