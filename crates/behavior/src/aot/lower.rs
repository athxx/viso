//! Bytecode to Rust: each chunk becomes a function whose registers are
//! locals and whose basic blocks are the arms of a block machine.

use alloc::borrow::ToOwned;
use alloc::collections::BTreeSet;
use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;
use core::fmt::Write;

use crate::module::{Chunk, ChunkKind, Code, Module};
use crate::op::Op;
use crate::value::Value;
use crate::vm::native_code::build_hash;

/// The Rust module running `module`'s systems: one function per chunk they
/// reach, and a `NATIVE` table of them for
/// [`Vm::install_native`](crate::Vm::install_native). `krate` is the path the
/// generated code names this crate by (`viso_behavior`, or a re-export).
///
/// The output is deterministic: the same module lowers to the same text.
pub fn lower_systems(module: &Module, krate: &str) -> String {
    lower(
        module,
        krate,
        &reachable(module),
        "lower_systems",
        "the systems'",
    )
}

/// The Rust module running every chunk of `module`: each handler, region
/// entry, computed value, effect, initializer, function and closure, and each
/// task as a resumable state machine. With it installed a component runs
/// without the interpreter. `krate` is the path the generated code
/// names this crate by.
///
/// The output is deterministic: the same module lowers to the same text.
pub fn lower_module(module: &Module, krate: &str) -> String {
    let all: BTreeSet<u32> = (0..module.chunks().len() as u32).collect();
    lower(module, krate, &all, "lower_module", "the module's")
}

fn lower(module: &Module, krate: &str, chunks: &BTreeSet<u32>, by: &str, whose: &str) -> String {
    let mut out = String::new();
    let build = build_hash(module);
    let _ = write!(
        out,
        "//! Generated by `{by}` from build {build:#018x}: {whose}\n\
         //! chunks compiled to Rust. Do not edit; regenerate from the module.\n\n\
         #![allow(unused_mut, unused_variables, unused_assignments, unused_imports)]\n\
         #![allow(unreachable_code, unreachable_patterns, non_snake_case)]\n\
         #![allow(clippy::all, clippy::pedantic, clippy::nursery)]\n\n\
         use {krate}::aot::{{self as rt, NativeCode, PathStep, Poll, TaskFrame}};\n\
         use {krate}::{{Arith, ArithOp, DisplayKind, FaultKind, Instance, Num, Value, Vm}};\n\n\
         macro_rules! t {{\n    ($vm:ident, $c:expr, $pc:expr, $e:expr) => {{\n        \
         match $e {{\n            Ok(v) => v,\n            Err(k) => return Err(rt::at($vm, $c, $pc, k)),\n        \
         }}\n    }};\n}}\n\n\
         /// The compiled chunks, for `Vm::install_native`.\n\
         pub static NATIVE: NativeCode = NativeCode {{\n    build: {build:#018x},\n    chunks: &[\n"
    );
    let compiled: Vec<u32> = chunks
        .iter()
        .copied()
        .filter(|&c| {
            module.chunk(c).body.code().is_some() && module.chunk(c).kind != ChunkKind::Task
        })
        .collect();
    let resumable = resumable(module, chunks);
    for c in &compiled {
        let _ = writeln!(out, "        ({c}, s{c}),");
    }
    out.push_str("    ],\n    resumable: &[\n");
    for c in &resumable {
        let _ = writeln!(out, "        ({c}, t{c}),");
    }
    out.push_str("    ],\n};\n");
    for &c in chunks {
        let chunk = module.chunk(c);
        let Some(code) = chunk.body.code() else {
            continue;
        };
        let lower = Lower {
            module,
            c,
            code,
            frame: false,
            resumable: &resumable,
        };
        if compiled.contains(&c) {
            lower.chunk(&mut out, chunk);
        }
        if resumable.contains(&c) {
            Lower {
                frame: true,
                ..lower
            }
            .chunk(&mut out, chunk);
        }
    }
    out
}

/// The chunks among `chunks` that can await work inside a task, so a task
/// runs them as resumable frames: the tasks, every chunk calling a native or
/// an unknown closure, and every chunk calling one of those.
fn resumable(module: &Module, chunks: &BTreeSet<u32>) -> BTreeSet<u32> {
    let calls = |c: u32| -> Vec<u32> {
        let Some(code) = module.chunk(c).body.code() else {
            return Vec::new();
        };
        code.ops
            .iter()
            .filter_map(|op| match *op {
                Op::Call { ext, .. } => Some(code.ext[ext as usize]),
                _ => None,
            })
            .collect()
    };
    let mut set: BTreeSet<u32> = chunks
        .iter()
        .copied()
        .filter(|&c| {
            let chunk = module.chunk(c);
            let Some(code) = chunk.body.code() else {
                return false;
            };
            chunk.kind == ChunkKind::Task
                || code
                    .ops
                    .iter()
                    .any(|op| matches!(op, Op::Native { .. } | Op::CallValue { .. }))
        })
        .collect();
    loop {
        let more: Vec<u32> = chunks
            .iter()
            .copied()
            .filter(|&c| !set.contains(&c) && module.chunk(c).body.code().is_some())
            .filter(|&c| calls(c).iter().any(|callee| set.contains(callee)))
            .collect();
        if more.is_empty() {
            break;
        }
        set.extend(more);
    }
    // Only what a task can reach needs a frame.
    let mut needed = BTreeSet::new();
    let mut stack: Vec<u32> = chunks
        .iter()
        .copied()
        .filter(|&c| {
            module.chunk(c).kind == ChunkKind::Task && module.chunk(c).body.code().is_some()
        })
        .collect();
    while let Some(c) = stack.pop() {
        if !set.contains(&c) || !needed.insert(c) {
            continue;
        }
        let Some(code) = module.chunk(c).body.code() else {
            continue;
        };
        for op in code.ops.iter() {
            if let Op::Call { ext, .. } | Op::Closure { ext, .. } = *op {
                stack.push(code.ext[ext as usize]);
            }
        }
    }
    // A closure a task may call through a value: every closure body that can
    // await.
    for &c in &set {
        if module.chunk(c).kind == ChunkKind::Closure {
            needed.insert(c);
        }
    }
    needed
}

/// The chunks the systems run, ascending: their hooks and state
/// initializers, and every chunk those call or close over.
fn reachable(module: &Module) -> BTreeSet<u32> {
    let mut seen = BTreeSet::new();
    let mut stack: Vec<u32> = Vec::new();
    for system in module.systems() {
        stack.extend(system.hooks.iter().map(|&(_, chunk)| chunk));
        let layout = module.layout(system.component);
        stack.extend(layout.state_inits.iter().flatten().copied());
        stack.extend(layout.input_defaults.iter().flatten().copied());
    }
    while let Some(c) = stack.pop() {
        if !seen.insert(c) {
            continue;
        }
        let Some(code) = module.chunk(c).body.code() else {
            continue;
        };
        for op in code.ops.iter() {
            match *op {
                Op::Call { ext, .. } | Op::Closure { ext, .. } | Op::Start { ext } => {
                    stack.push(code.ext[ext as usize]);
                }
                _ => {}
            }
        }
    }
    seen
}

/// Whether control does not fall through `op` to the next.
fn ends_block(op: &Op) -> bool {
    matches!(
        op,
        Op::Jump { .. }
            | Op::JumpIf { .. }
            | Op::JumpUnless { .. }
            | Op::Switch { .. }
            | Op::Return { .. }
            | Op::Unreachable
    )
}

/// The first op of every basic block of `code`, ascending.
fn leaders(code: &Code) -> BTreeSet<usize> {
    let mut leaders = BTreeSet::from([0]);
    for (i, op) in code.ops.iter().enumerate() {
        match *op {
            Op::Jump { target } => {
                leaders.insert(target as usize);
            }
            Op::JumpIf { target, .. } | Op::JumpUnless { target, .. } => {
                leaders.insert(target as usize);
            }
            Op::Switch { ext, .. } => {
                let at = ext as usize;
                leaders.insert(code.ext[at + 2] as usize);
                let n = code.ext[at + 3] as usize;
                leaders.extend(code.ext[at + 4..at + 4 + n].iter().map(|&t| t as usize));
            }
            _ => {}
        }
        if ends_block(op) {
            leaders.insert(i + 1);
        }
    }
    leaders.retain(|&l| l < code.ops.len());
    leaders
}

/// One chunk being lowered: as a function whose registers are locals, or,
/// with `frame`, as a resumable function whose registers live in a
/// [`TaskFrame`](crate::aot::TaskFrame) so a task can suspend in it.
#[derive(Clone, Copy)]
struct Lower<'a> {
    module: &'a Module,
    c: u32,
    code: &'a Code,
    frame: bool,
    resumable: &'a BTreeSet<u32>,
}

impl Lower<'_> {
    /// Register `n`.
    fn r(&self, n: impl Into<u32>) -> String {
        let n = n.into();
        if self.frame {
            format!("f.regs[{n}]")
        } else {
            format!("r{n}")
        }
    }

    /// The clones of the registers `regs`, comma-separated.
    fn clones(&self, regs: &[u32]) -> String {
        regs.iter()
            .map(|&x| format!("{}.clone()", self.r(x)))
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn chunk(&self, out: &mut String, chunk: &Chunk) {
        let c = self.c;
        let params = u32::from(chunk.params);
        let captures: Vec<u32> = chunk.captures.iter().map(|&x| u32::from(x)).collect();
        if self.frame {
            let _ = write!(
                out,
                "\n/// {:?} (chunk {c}), resumable.\nfn t{c}(vm: &mut Vm, inst: &mut Instance, depth: usize, f: &mut TaskFrame) -> Result<Poll, FaultKind> {{\n",
                &*chunk.name
            );
        } else {
            let mut signature: Vec<String> = (0..params)
                .map(|p| format!("mut {}: Value", self.r(p)))
                .collect();
            signature.extend(
                captures
                    .iter()
                    .map(|&x| format!("mut {}: Value", self.r(x))),
            );
            let _ = write!(
                out,
                "\n/// {:?} (chunk {c}).\nfn c{c}(vm: &mut Vm, inst: &mut Instance, depth: usize{}{}) -> Result<Value, FaultKind> {{\n",
                &*chunk.name,
                if signature.is_empty() { "" } else { ", " },
                signature.join(", ")
            );
            for x in 0..u32::from(chunk.regs) {
                if x >= params && !captures.contains(&x) {
                    let _ = writeln!(out, "    let mut {} = Value::Nil;", self.r(x));
                }
            }
        }
        let pooled = self.code.ops.iter().any(|op| match *op {
            Op::Const { index, .. } => literal(&self.code.consts[index as usize]).is_none(),
            _ => false,
        });
        if pooled {
            let _ = writeln!(
                out,
                "    let module = rt::module(vm);\n    let k = rt::consts(&module, {c});"
            );
        }
        if self.frame {
            out.push_str("    loop {\n        match f.pc {\n");
        } else {
            out.push_str("    let mut pc: u32 = 0;\n    loop {\n        match pc {\n");
        }
        let leaders = self.leaders();
        let starts: Vec<usize> = leaders.iter().copied().collect();
        for (b, &start) in starts.iter().enumerate() {
            let end = starts.get(b + 1).copied().unwrap_or(self.code.ops.len());
            let _ = writeln!(out, "            {start} => {{");
            for i in start..end {
                self.op(out, i);
            }
            if !ends_block(&self.code.ops[end - 1]) {
                let _ = writeln!(
                    out,
                    "                {} = {end};\n                continue;",
                    self.pc()
                );
            }
            out.push_str("            }\n");
        }
        let _ = writeln!(
            out,
            "            _ => return Err(rt::at(vm, {c}, 0, FaultKind::Internal)),\n        }}\n    }}\n}}"
        );
        if self.frame {
            return;
        }
        // The uniform entry the table holds.
        let mut args: Vec<String> = (0..params).map(|p| format!("args[{p}].clone()")).collect();
        args.extend((0..captures.len()).map(|i| format!("caps[{i}].clone()")));
        let _ = writeln!(
            out,
            "\nfn s{c}(vm: &mut Vm, inst: &mut Instance, depth: usize, args: &[Value], caps: &[Value]) -> Result<Value, FaultKind> {{\n    c{c}(vm, inst, depth{}{})\n}}",
            if args.is_empty() { "" } else { ", " },
            args.join(", ")
        );
    }

    /// The program counter's place.
    fn pc(&self) -> &'static str {
        if self.frame { "f.pc" } else { "pc" }
    }

    /// The first op of every basic block, ascending. In a resumable chunk a
    /// call that can suspend is a block of its own, re-entered on resume.
    fn leaders(&self) -> BTreeSet<usize> {
        let mut leaders = leaders(self.code);
        if self.frame {
            for (i, op) in self.code.ops.iter().enumerate() {
                if self.suspends(op) {
                    leaders.insert(i);
                    leaders.insert(i + 1);
                } else if matches!(op, Op::Native { .. }) {
                    // A task native's work resumes the task past it.
                    leaders.insert(i + 1);
                }
            }
            leaders.retain(|&l| l < self.code.ops.len());
        }
        leaders
    }

    /// Whether `op`, in a resumable chunk, calls into a resumable frame.
    fn suspends(&self, op: &Op) -> bool {
        match *op {
            Op::Call { ext, .. } => self.resumable.contains(&self.code.ext[ext as usize]),
            Op::CallValue { .. } => true,
            _ => false,
        }
    }

    fn op(&self, out: &mut String, i: usize) {
        let Lower {
            module, c, code, ..
        } = *self;
        let op = code.ops[i];
        let ext = |at: u32| &code.ext[at as usize..];
        // A fault of the op itself, with the interpreter's cursor past it.
        let t = |e: &str| format!("t!(vm, {c}, {}, {e})", i + 1);
        let r = |n: u32| self.r(n);
        let mut line = |s: String| {
            let _ = writeln!(out, "                {s}");
        };
        let pc = self.pc();
        let tick = format!("t!(vm, {c}, {i}, rt::tick(vm));");
        if !(self.frame && self.suspends(&op)) {
            line(tick.clone());
        }
        match op {
            Op::Const { dst, index } => {
                let value = &code.consts[index as usize];
                let expr = literal(value).unwrap_or_else(|| format!("k[{index}].clone()"));
                line(format!("{} = {expr};", r(dst.into())));
            }
            Op::Int { dst, value } => line(format!("{} = Value::Int({value});", r(dst.into()))),
            Op::Nil { dst } => line(format!("{} = Value::Nil;", r(dst.into()))),
            Op::Move { dst, src } => {
                if dst != src {
                    line(format!("{} = {}.clone();", r(dst.into()), r(src.into())));
                }
            }
            Op::LoadState { dst, slot } => {
                line(format!(
                    "{} = {};",
                    r(dst.into()),
                    t(&format!("rt::load_state(vm, inst, {slot})"))
                ));
            }
            Op::StoreState { src, slot } => line(format!(
                "{};",
                t(&format!(
                    "rt::store_state(vm, inst, {slot}, {}.clone())",
                    r(src.into())
                ))
            )),
            Op::LoadInput { dst, slot } => {
                line(format!(
                    "{} = {};",
                    r(dst.into()),
                    t(&format!("rt::load_input(vm, inst, {slot})"))
                ));
            }
            Op::AddI64 { dst, a, b } | Op::SubI64 { dst, a, b } | Op::MulI64 { dst, a, b } => {
                let method = match op {
                    Op::AddI64 { .. } => "checked_add",
                    Op::SubI64 { .. } => "checked_sub",
                    _ => "checked_mul",
                };
                line(format!(
                    "{} = Value::Int({});",
                    r(dst.into()),
                    t(&format!(
                        "{}.{method}({}).ok_or(FaultKind::Overflow)",
                        t(&format!("rt::int(&{})", r(a.into()))),
                        t(&format!("rt::int(&{})", r(b.into())))
                    ))
                ));
            }
            Op::LtI64 { dst, a, b } | Op::LeI64 { dst, a, b } => {
                let cmp = if matches!(op, Op::LtI64 { .. }) {
                    "<"
                } else {
                    "<="
                };
                line(format!(
                    "{} = Value::bool({} {cmp} {});",
                    r(dst.into()),
                    t(&format!("rt::int(&{})", r(a.into()))),
                    t(&format!("rt::int(&{})", r(b.into())))
                ));
            }
            Op::AddF64 { dst, a, b }
            | Op::SubF64 { dst, a, b }
            | Op::MulF64 { dst, a, b }
            | Op::DivF64 { dst, a, b } => {
                let sym = match op {
                    Op::AddF64 { .. } => "+",
                    Op::SubF64 { .. } => "-",
                    Op::MulF64 { .. } => "*",
                    _ => "/",
                };
                line(format!(
                    "{} = Value::Float({} {sym} {});",
                    r(dst.into()),
                    t(&format!("rt::float(&{})", r(a.into()))),
                    t(&format!("rt::float(&{})", r(b.into())))
                ));
            }
            Op::LtF64 { dst, a, b } | Op::LeF64 { dst, a, b } => {
                let cmp = if matches!(op, Op::LtF64 { .. }) {
                    "<"
                } else {
                    "<="
                };
                line(format!(
                    "{} = Value::bool({} {cmp} {});",
                    r(dst.into()),
                    t(&format!("rt::float(&{})", r(a.into()))),
                    t(&format!("rt::float(&{})", r(b.into())))
                ));
            }
            Op::Arith { op, dst, a, b } => line(format!(
                "{} = {};",
                r(dst.into()),
                t(&format!(
                    "rt::arith(ArithOp::new(Arith::{:?}, Num::{:?}), &{}, &{})",
                    op.op(),
                    op.num(),
                    r(a.into()),
                    r(b.into())
                ))
            )),
            Op::Eq { dst, a, b } => line(format!(
                "{} = Value::bool({} == {});",
                r(dst.into()),
                r(a.into()),
                r(b.into())
            )),
            Op::Ne { dst, a, b } => line(format!(
                "{} = Value::bool({} != {});",
                r(dst.into()),
                r(a.into()),
                r(b.into())
            )),
            Op::Neg { num, dst, src } => line(format!(
                "{} = {};",
                r(dst.into()),
                t(&format!("rt::neg(Num::{num:?}, &{})", r(src.into())))
            )),
            Op::Not { dst, src } => line(format!(
                "{} = Value::bool({} == 0);",
                r(dst.into()),
                t(&format!("rt::int(&{})", r(src.into())))
            )),
            Op::BitNot { num, dst, src } => line(format!(
                "{} = {};",
                r(dst.into()),
                t(&format!("rt::bit_not(Num::{num:?}, &{})", r(src.into())))
            )),
            Op::Cast { from, to, dst, src } => line(format!(
                "{} = {};",
                r(dst.into()),
                t(&format!(
                    "rt::cast(Num::{from:?}, Num::{to:?}, &{})",
                    r(src.into())
                ))
            )),
            Op::Call { dst, ext: at } => {
                let e = ext(at);
                let (func, argc) = (e[0], e[1] as usize);
                let args = &e[2..2 + argc];
                let callee = module.chunk(func);
                if self.frame && self.resumable.contains(&func) {
                    // Enter the callee's frame once; poll it until it returns.
                    let mut call: Vec<String> =
                        args.iter().map(|&x| format!("{}.clone()", r(x))).collect();
                    call.extend(callee.captures.iter().map(|_| "Value::Nil".to_owned()));
                    line(format!("if f.child.is_none() {{ {tick}"));
                    line(format!(
                        "    match {} {{ Some(v) => {{ {} = v; f.pc = {}; continue; }} None => {{}} }}",
                        t(&format!("rt::memo_enter(vm, inst, {func})")),
                        r(dst.into()),
                        i + 1
                    ));
                    line(format!(
                        "    {}; f.child = Some(Box::new(rt::frame(vm, {func}, vec![{}])));",
                        t("rt::depth(vm, depth)"),
                        call.join(", ")
                    ));
                    line("}".to_owned());
                    line(format!(
                        "match t{func}(vm, inst, depth + 1, f.child.as_deref_mut().unwrap())? {{ Poll::Ready(v) => {{ f.child = None; {} = v; }} Poll::Pending => return Ok(Poll::Pending) }}",
                        r(dst.into())
                    ));
                    line(format!("f.pc = {};\n                continue;", i + 1));
                    return;
                }
                line(format!(
                    "{} = match {} {{",
                    r(dst.into()),
                    t(&format!("rt::memo_enter(vm, inst, {func})"))
                ));
                line("    Some(v) => v,".to_owned());
                if callee.body.code().is_some() {
                    let mut call: Vec<String> =
                        args.iter().map(|&x| format!("{}.clone()", r(x))).collect();
                    call.extend(callee.captures.iter().map(|_| "Value::Nil".to_owned()));
                    line(format!(
                        "    None => {{ {}; c{func}(vm, inst, depth + 1{}{})? }}",
                        t("rt::depth(vm, depth)"),
                        if call.is_empty() { "" } else { ", " },
                        call.join(", ")
                    ));
                } else {
                    line(format!(
                        "    None => {{ let k = rt::unsupported(vm, {func}); return Err(rt::at(vm, {c}, {}, k)); }}",
                        i + 1
                    ));
                }
                line("};".to_owned());
            }
            Op::CallValue { dst, ext: at } => {
                let e = ext(at);
                let argc = e[1] as usize;
                if self.frame {
                    // A closure that can await runs in a frame of its own;
                    // any other closure is an ordinary call.
                    let (callee, args) = (r(e[0]), self.clones(&e[2..2 + argc]));
                    line(format!("if f.child.is_none() {{ {tick}"));
                    line(format!("    {};", t("rt::depth(vm, depth)")));
                    line(format!(
                        "    match {} {{ Some(child) => f.child = Some(Box::new(child)), None => {{ {} = {}; f.pc = {}; continue; }} }}",
                        t(&format!("rt::closure_frame(vm, &{callee}, vec![{args}])")),
                        r(dst.into()),
                        t(&format!(
                            "rt::call_value(vm, inst, depth, &{callee}, &[{args}])"
                        )),
                        i + 1
                    ));
                    line("}".to_owned());
                    line(format!(
                        "match {} {{ Poll::Ready(v) => {{ f.child = None; {} = v; }} Poll::Pending => return Ok(Poll::Pending) }}",
                        t("rt::resume_frame(vm, inst, depth + 1, f.child.as_deref_mut().unwrap())"),
                        r(dst.into())
                    ));
                    line(format!("f.pc = {};\n                continue;", i + 1));
                    return;
                }
                line(format!(
                    "{} = {};",
                    r(dst.into()),
                    t(&format!(
                        "rt::call_value(vm, inst, depth, &{}, &[{}])",
                        r(e[0]),
                        self.clones(&e[2..2 + argc])
                    ))
                ));
            }
            Op::Native { dst, ext: at } => {
                let e = ext(at);
                let argc = e[1] as usize;
                let mut s = String::from("{ let mut a = rt::scratch(vm); ");
                for &x in &e[2..2 + argc] {
                    let _ = write!(s, "a.push({}.clone()); ", r(x));
                }
                if self.frame {
                    let _ = write!(
                        s,
                        "let (v, awaits) = {}; {} = v; if awaits {{ f.dst = {dst}; f.pc = {}; return Ok(Poll::Pending); }} }}",
                        t(&format!("rt::native_task(vm, {}, a)", e[0])),
                        r(dst.into()),
                        i + 1
                    );
                } else {
                    let _ = write!(
                        s,
                        "{} = {}; }}",
                        r(dst.into()),
                        t(&format!("rt::native(vm, {}, a)", e[0]))
                    );
                }
                line(s);
            }
            Op::Closure { dst, ext: at } => {
                let e = ext(at);
                let n = e[1] as usize;
                line(format!(
                    "{} = {};",
                    r(dst.into()),
                    t(&format!(
                        "rt::closure(vm, {}, Box::from([{}]))",
                        e[0],
                        self.clones(&e[2..2 + n])
                    ))
                ));
            }
            Op::Make { dst, ext: at } => {
                let e = ext(at);
                let n = e[1] as usize;
                line(format!(
                    "{} = {};",
                    r(dst.into()),
                    t(&format!(
                        "rt::make(vm, {}, Box::from([{}]))",
                        e[0],
                        self.clones(&e[2..2 + n])
                    ))
                ));
            }
            Op::List { dst, ext: at } => {
                let e = ext(at);
                let n = e[0] as usize;
                line(format!(
                    "{} = {};",
                    r(dst.into()),
                    t(&format!(
                        "rt::list(vm, vec![{}])",
                        self.clones(&e[1..1 + n])
                    ))
                ));
            }
            Op::Concat { dst, ext: at } => {
                let e = ext(at);
                let n = e[0] as usize;
                let parts: Vec<String> =
                    e[1..1 + n].iter().map(|&x| format!("&{}", r(x))).collect();
                line(format!(
                    "{} = {};",
                    r(dst.into()),
                    t(&format!("rt::concat(vm, &[{}])", parts.join(", ")))
                ));
            }
            Op::Translate { dst, ext: at } => {
                let e = ext(at);
                let n = e[2] as usize;
                let mut s = String::from("{ let mut a = rt::scratch(vm); ");
                for &x in &e[3..3 + n] {
                    let _ = write!(s, "a.push({}.clone()); ", r(x));
                }
                let _ = write!(
                    s,
                    "{} = {}; }}",
                    r(dst.into()),
                    t(&format!("rt::translate(vm, &{}, &{}, a)", r(e[0]), r(e[1])))
                );
                line(s);
            }
            Op::Field { dst, src, index } => line(format!(
                "{} = {};",
                r(dst.into()),
                t(&format!("rt::field(&{}, {index})", r(src.into())))
            )),
            Op::Index { dst, list, index } => line(format!(
                "{} = {};",
                r(dst.into()),
                t(&format!(
                    "rt::index(vm, &{}, &{})",
                    r(list.into()),
                    r(index.into())
                ))
            )),
            Op::SetPath { root, ext: at } => {
                let e = ext(at);
                let n = e[1] as usize;
                // Index operands are read before the root is borrowed.
                let mut held = String::new();
                let steps: Vec<String> = e[2..2 + 2 * n]
                    .chunks(2)
                    .enumerate()
                    .map(|(k, step)| match step[0] {
                        0 => format!("PathStep::Field({})", step[1]),
                        // The interpreter has taken the root out of its register.
                        _ if step[1] == u32::from(root) => {
                            "PathStep::Index(&Value::Nil)".to_owned()
                        }
                        _ => {
                            let _ = write!(held, "let i{k} = {}.clone(); ", r(step[1]));
                            format!("PathStep::Index(&i{k})")
                        }
                    })
                    .collect();
                line(format!(
                    "{{ let src = {}.clone(); {held}{}; }}",
                    r(e[0]),
                    t(&format!(
                        "rt::set_path(vm, &mut {}, &[{}], src)",
                        r(root.into()),
                        steps.join(", ")
                    ))
                ));
            }
            Op::Push { list, item } => line(format!(
                "{{ let item = {}.clone(); {}; }}",
                r(item.into()),
                t(&format!("rt::push(vm, &mut {}, item)", r(list.into())))
            )),
            Op::Insert { list, index, item } => line(format!(
                "{{ let index = {}.clone(); let item = {}.clone(); {}; }}",
                r(index.into()),
                r(item.into()),
                t(&format!(
                    "rt::insert(vm, &mut {}, &index, item)",
                    r(list.into())
                ))
            )),
            Op::Remove { dst, list, index } => line(format!(
                "{{ let index = {}.clone(); {} = {}; }}",
                r(index.into()),
                r(dst.into()),
                t(&format!("rt::remove(vm, &mut {}, &index)", r(list.into())))
            )),
            Op::Truncate { list, len } => line(format!(
                "{{ let len = {}.clone(); {}; }}",
                r(len.into()),
                t(&format!("rt::truncate(vm, &mut {}, &len)", r(list.into())))
            )),
            Op::Len { dst, src } => line(format!(
                "{} = {};",
                r(dst.into()),
                t(&format!("rt::len(&{})", r(src.into())))
            )),
            Op::Tag { dst, src } => line(format!(
                "{} = {};",
                r(dst.into()),
                t(&format!("rt::tag(&{})", r(src.into())))
            )),
            Op::IsNil { dst, src } => line(format!(
                "{} = Value::bool({}.is_nil());",
                r(dst.into()),
                r(src.into())
            )),
            Op::Jump { target } => line(format!("{pc} = {target};\n                continue;")),
            Op::JumpIf { cond, target } | Op::JumpUnless { cond, target } => {
                let cmp = if matches!(op, Op::JumpIf { .. }) {
                    "!="
                } else {
                    "=="
                };
                line(format!(
                    "{pc} = if {} {cmp} 0 {{ {target} }} else {{ {} }};\n                continue;",
                    t(&format!("rt::int(&{})", r(cond.into()))),
                    i + 1
                ));
            }
            Op::Switch { src, ext: at } => {
                let e = ext(at);
                let first = ((u64::from(e[1]) << 32) | u64::from(e[0])) as i64;
                let (default, n) = (e[2], e[3] as usize);
                let mut s = format!(
                    "{pc} = match {}.checked_sub({}) {{ ",
                    t(&format!("rt::int(&{})", r(src.into()))),
                    if first == i64::MIN {
                        "i64::MIN".to_owned()
                    } else {
                        format!("{first}")
                    }
                );
                for (k, &target) in e[4..4 + n].iter().enumerate() {
                    let _ = write!(s, "Some({k}) => {target}, ");
                }
                let _ = write!(s, "_ => {default} }};\n                continue;");
                line(s);
            }
            Op::Return { src } => {
                let value = format!(
                    "rt::ret(vm, inst, {c}, std::mem::take(&mut {}))",
                    r(src.into())
                );
                if self.frame {
                    line(format!("return Ok(Poll::Ready({value}));"));
                } else {
                    line(format!("return Ok({value});"));
                }
            }
            Op::Emit { ext: at } => {
                let e = ext(at);
                let n = e[1] as usize;
                line(format!(
                    "{};",
                    t(&format!(
                        "rt::emit(vm, {}, Box::from([{}]))",
                        e[0],
                        self.clones(&e[2..2 + n])
                    ))
                ));
            }
            Op::Node { dst, ext: at } => {
                let e = ext(at);
                let n = e[2] as usize;
                line(format!(
                    "{} = {};",
                    r(dst.into()),
                    t(&format!(
                        "rt::node(vm, {}, &{}, Box::from([{}]))",
                        e[0],
                        r(e[1]),
                        self.clones(&e[3..3 + n])
                    ))
                ));
            }
            Op::Start { ext: at } => {
                let e = ext(at);
                let argc = e[1] as usize;
                let tail = &e[2 + argc..7 + argc];
                let handler = |x: u32| {
                    if x == u32::MAX {
                        "None".to_owned()
                    } else {
                        format!("Some({}.clone())", r(x))
                    }
                };
                line(format!(
                    "{};",
                    t(&format!(
                        "rt::start(vm, {}, Box::from([{}]), {}, {}, {}, {}, {})",
                        e[0],
                        self.clones(&e[2..2 + argc]),
                        handler(tail[0]),
                        handler(tail[1]),
                        tail[2],
                        tail[3],
                        tail[4]
                    ))
                ));
            }
            Op::Display { kind, dst, src } => line(format!(
                "{} = {};",
                r(dst.into()),
                t(&format!(
                    "rt::display(vm, DisplayKind::{kind:?}, &{})",
                    r(src.into())
                ))
            )),
            Op::DisplayDim { dst, src, suffix } => {
                let suffix = code.consts[usize::from(suffix)]
                    .as_str()
                    .unwrap_or_default();
                line(format!(
                    "{} = {};",
                    r(dst.into()),
                    t(&format!(
                        "rt::display_dim(vm, &{}, {suffix:?})",
                        r(src.into())
                    ))
                ));
            }
            Op::Unreachable => line(format!(
                "{{ let k = rt::unreachable(vm); return Err(rt::at(vm, {c}, {}, k)); }}",
                i + 1
            )),
        }
    }
}

/// A Rust expression of the scalar constant `value`, if it is one.
fn literal(value: &Value) -> Option<String> {
    Some(match value {
        Value::Nil => "Value::Nil".to_owned(),
        Value::Int(i64::MIN) => "Value::Int(i64::MIN)".to_owned(),
        Value::Int(n) => format!("Value::Int({n})"),
        Value::Float(x) => format!("Value::Float(f64::from_bits({:#x}))", x.to_bits()),
        _ => return None,
    })
}
