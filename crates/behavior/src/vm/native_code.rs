/// `state[slot]`. A task that suspended reads no state any more.
#[inline]
pub fn load_state(vm: &Vm, inst: &Instance, slot: u32) -> Step<Value> {
    if vm.resumed {
        return Err(FaultKind::SuspendedRead);
    }
    inst.states
        .get(slot as usize)
        .cloned()
        .ok_or(FaultKind::Internal)
}

/// `state[slot] = value`, undone if the transaction faults.
#[inline]
pub fn store_state(vm: &mut Vm, inst: &mut Instance, slot: u32, value: Value) -> Step<()> {
    let Some(target) = inst.states.get_mut(slot as usize) else {
        return Err(FaultKind::Internal);
    };
    let (word, bit) = (slot as usize / 64, 1u64 << (slot % 64));
    if vm.marks[word] & bit == 0 {
        vm.marks[word] |= bit;
        vm.undo.push((slot, mem::replace(target, value)));
    } else {
        *target = value;
    }
    if vm.memo {
        inst.forget_state(slot as usize);
    }
    Ok(())
}

/// `input[slot]`. A task that suspended reads no input any more.
#[inline]
pub fn load_input(vm: &Vm, inst: &Instance, slot: u32) -> Step<Value> {
    if vm.resumed {
        return Err(FaultKind::SuspendedRead);
    }
    inst.inputs
        .get(slot as usize)
        .cloned()
        .ok_or(FaultKind::Internal)
}

