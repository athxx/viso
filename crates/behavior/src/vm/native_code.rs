/// A chunk compiled to Rust: the VM, the instance, the call depth, the
/// arguments and the captured values.
pub type NativeFn = fn(&mut Vm, &mut Instance, usize, &[Value], &[Value]) -> Step<Value>;

/// A chunk compiled to Rust as a resumable function, for a task: it runs
/// `frame` from its program counter until it returns or awaits.
pub type ResumableFn = fn(&mut Vm, &mut Instance, usize, &mut TaskFrame) -> Step<Poll>;

/// The chunks of one build compiled to Rust, generated by
/// [`lower_module`](crate::aot::lower_module) or
/// [`lower_systems`](crate::aot::lower_systems) and installed with
/// [`Vm::install_native`].
#[derive(Debug)]
pub struct NativeCode {
    /// The hash of the module the code was lowered from.
    pub build: u64,
    /// Each compiled chunk, by index.
    pub chunks: &'static [(u32, NativeFn)],
    /// Each chunk a task can await in, compiled as a resumable function.
    pub resumable: &'static [(u32, ResumableFn)],
}

/// Where a resumable function stopped.
#[derive(Debug)]
pub enum Poll {
    /// It returned this value.
    Ready(Value),
    /// It awaits the work a task native handed over.
    Pending,
}

/// One frame of a compiled task's call stack: the registers of a resumable
/// chunk, where it continues, and the frame of the resumable call it awaits
/// in, if any.
#[derive(Debug, Clone)]
pub struct TaskFrame {
    /// The chunk.
    pub chunk: u32,
    /// Its registers.
    pub regs: Vec<Value>,
    /// The op it continues at.
    pub pc: u32,
    /// The register the awaited native's value lands in.
    pub dst: u16,
    /// The frame of the call it awaits in.
    pub child: Option<Box<TaskFrame>>,
}

impl TaskFrame {
    /// The innermost frame: the one awaiting a native.
    pub fn innermost(&mut self) -> &mut TaskFrame {
        if self.child.is_some() {
            self.child.as_deref_mut().unwrap().innermost()
        } else {
            self
        }
    }
}

/// Compiled code lowered from another build than the module it was
/// installed for.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct NativeCodeMismatch {
    /// The module's build hash.
    pub expected: u64,
    /// The build hash the code was lowered from.
    pub found: u64,
}

impl fmt::Display for NativeCodeMismatch {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "the compiled code was lowered from build {:#018x}, not this module's {:#018x}",
            self.found, self.expected
        )
    }
}

impl core::error::Error for NativeCodeMismatch {}

/// The build hash of `module`: 64-bit FNV-1a of its encoding, the hash a
/// game's snapshots carry. A [`compiled`](Module::compiled) module has the
/// hash of the module it was compiled from.
pub fn build_hash(module: &Module) -> u64 {
    module
        .build
        .unwrap_or_else(|| viso_ende::content_hash(&module.encode()))
}

/// One step of a [`set_path`] write.
#[derive(Debug, Clone, Copy)]
pub enum PathStep<'a> {
    /// Field `index` of an aggregate.
    Field(u32),
    /// The list element at the index this register holds.
    Index(&'a Value),
}

/// Spends one unit of fuel for the next op.
#[inline(always)]
pub fn tick(vm: &mut Vm) -> Step<()> {
    if vm.fuel == 0 {
        return Err(FaultKind::InstructionBudget);
    }
    vm.fuel -= 1;
    Ok(())
}

/// Records that `kind` faulted in `chunk` with the interpreter's cursor at
/// `pc`, unless a callee already recorded where it faulted.
#[cold]
pub fn at(vm: &mut Vm, chunk: u32, pc: usize, kind: FaultKind) -> FaultKind {
    if vm.native_at.is_none() {
        vm.native_at = Some((chunk, pc));
    }
    kind
}

