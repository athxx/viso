//! The runtime of chunks compiled to Rust (`crate::aot`): what the lowered
//! code of each op calls, with the interpreter's semantics.
//!
//! Lowered code keeps a chunk's registers in Rust locals and its control flow
//! in a block machine; every op spends one unit of fuel first ([`tick`]), and
//! a fault records where the interpreter's cursor would have been ([`at`]),
//! so a compiled invocation spends, faults and rolls back exactly as an
//! interpreted one.

